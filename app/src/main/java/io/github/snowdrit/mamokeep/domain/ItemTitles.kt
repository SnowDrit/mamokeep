package io.github.snowdrit.mamokeep.domain

/**
 * Название позиции обслуживания.
 *
 * Домен хранит ключ (`oil`, `spark_plugs`), слово подставляет интерфейс из ресурсов —
 * тот же приём, что со значками и типами кузова (docs/DECISIONS.md, решение 22).
 *
 * Причина именно такая: человек, переключивший язык приложения, иначе получил бы
 * английский интерфейс поверх девяти русских позиций — то самое «выглядит как брошенный
 * проект», которого боялось решение 19.
 *
 * Переименовал позицию руками — ключ гаснет, дальше это его текст и трогать его нельзя.
 */
fun interface ItemTitles {
    /** @param stored то, что лежит в базе; используется, когда ключа нет. */
    fun resolve(key: String?, stored: String): String
}
