package io.github.snowdrit.mamokeep.domain

import java.time.LocalDate

/**
 * Событие в жизни машины.
 *
 * Заправка, выполненная работа и продление документа — события одного рода: что-то
 * произошло в такой-то день при таком-то пробеге. Поэтому одна лента, а не три списка.
 */
data class JournalEntry(
    val date: LocalDate,
    val km: Int?,
    /**
     * `null` у заправки: её заголовок один и тот же для всех записей и живёт в ресурсах.
     * Репозиторий не знает языка приложения — он и не должен, — поэтому подставляет его
     * экран. У работ и документов здесь настоящее название позиции.
     */
    val title: String?,
    /**
     * Заправка, из которой сделана строка. Не `null` только у [Kind.FUEL] — по нему
     * строка открывается на правку.
     */
    val fuelEntryId: Long? = null,
    /**
     * Запись в истории обслуживания — у работ и продлений документов. По ней строка
     * тоже открывается на правку: «Сделано» жмётся одним касанием, в том числе из
     * шторки, и промахнуться так же легко.
     */
    val recordId: Long? = null,
    /**
     * Позиция, которой запись принадлежит. Не `null` у работ и продлений.
     *
     * Нужна редактору: отметку можно перенести на другую позицию, а для этого надо знать,
     * с какой она уходит — «последний раз» пересчитывается у обеих.
     */
    val itemId: Long? = null,
    /**
     * Подробности заправки — числом, а не готовой строкой.
     *
     * Раньше строка собиралась в репозитории, но с появлением единиц измерения это
     * перестало быть возможным: литры это или галлоны, знает только экран, у которого
     * есть настройки. Данные наверх, показ вниз.
     */
    val fuel: Fuel?,
    val amountKopecks: Long?,
    val iconKey: String,
    val kind: Kind,
    val note: String? = null,
) {
    data class Fuel(val amount: Double, val fuelType: FuelType, val isFull: Boolean)

    enum class Kind { FUEL, WORK, DOCUMENT }
}
